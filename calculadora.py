#Calculadora simples

numero_1 = int(input("Primeiro numero: "))
numero_2 = int(input("Segundo numero: "))
soma = numero_1 + numero_2
subtracao = numero_1 - numero_2
mutiplicacao = numero_1 * numero_2

print(f"Número 1: {numero_1}")
print(f"Número 2: {numero_2}")
print(f"Soma: {soma}")
print(f"Subtração: {subtracao}")
print(f"Multiplicação: {mutiplicacao}")